from odoo import api, Command, fields, models, _
from odoo.exceptions import UserError


class SupplyAdoptMixin(models.AbstractModel):
    """Create a supply order out of an existing sale/purchase order, adopting what already happened."""
    _name = 'supply.adopt.mixin'
    _description = 'Create a supply order from an existing order'

    def _adopt_into_supply_order(self, supply, doc_lines, supply_lines, invoice_field):
        """Attach what already exists on this document (moves, invoice lines) to the new supply order."""
        self.supply_order_id = supply
        for doc_line, line in zip(doc_lines, supply_lines):
            doc_line.supply_line_id = line
            doc_line.move_ids.write({'supply_line_id': line.id})
            invoice_lines = doc_line[invoice_field].filtered(lambda i: i.move_id.state != 'cancel')
            invoice_lines.write({'supply_line_id': line.id})
            invoice_lines.move_id.write({'supply_order_id': supply.id})
        if self.state in ('sale', 'purchase', 'done'):
            supply.action_confirm()
        supply._post_app(_("Created from %s.", self.display_name))
        return {
            'type': 'ir.actions.act_window', 'res_model': 'supply.order', 'res_id': supply.id,
            'view_mode': 'form', 'name': _('Supply Order'),
        }

    def action_create_supply_order(self):
        self.ensure_one()
        if self.supply_order_id:
            raise UserError(_("%s already has a supply order.", self.display_name))
        doc_lines = self.order_line.filtered(lambda l: not l.display_type and l.product_id.type == 'consu')
        if not doc_lines:
            raise UserError(_("No stockable/consumable item to supply on %s.", self.display_name))
        supply = self.env['supply.order'].create(self._supply_order_vals(doc_lines))
        supply_lines = supply.line_ids.sorted('id')
        return self._adopt_into_supply_order(supply, doc_lines, supply_lines, 'invoice_lines')


class StockMove(models.Model):
    _inherit = 'stock.move'

    # copy=True on purpose: backorder moves are copies and must keep the supply link.
    supply_line_id = fields.Many2one('supply.order.line', string='Supply Order Line', index='btree_not_null',
                                     ondelete='set null')

    @api.model_create_multi
    def create(self, vals_list):
        # Moves generated by a sale/purchase order created from a supply order keep the supply link.
        for vals in vals_list:
            if vals.get('supply_line_id'):
                continue
            if vals.get('sale_line_id'):
                line = self.env['sale.order.line'].browse(vals['sale_line_id']).supply_line_id
            elif vals.get('purchase_line_id'):
                line = self.env['purchase.order.line'].browse(vals['purchase_line_id']).supply_line_id
            else:
                continue
            if line:
                vals['supply_line_id'] = line.id
        moves = super().create(vals_list)
        moves._supply_adopt_orphans()
        return moves

    def write(self, vals):
        relink = self.env['stock.move']
        if 'product_id' in vals and not self.env.context.get('supply_internal'):
            relink = self.filtered(
                lambda m: m.supply_line_id and m.state not in ('done', 'cancel')
                and m.supply_line_id.product_id.id != vals['product_id'])
        res = super().write(vals)
        if relink:
            relink._supply_relink()
        if 'product_uom_qty' in vals and not self.env.context.get('supply_internal'):
            self.supply_line_id._sync_requested_with_moves()
        return res

    def _supply_adopt_orphans(self):
        """Items typed straight into a transfer prepared from a supply order become supply lines."""
        for move in self:
            order = move.picking_id.supply_order_id
            if move.supply_line_id or not order or order.state != 'confirmed':
                continue
            if move.sale_line_id or move.purchase_line_id:
                continue
            order._add_line_from_move(move)

    def _supply_relink(self):
        """The item of a planned move was changed in the transfer: follow it to the line of the new item."""
        for move in self:
            order = move.supply_line_id.order_id
            order._add_line_from_move(move)
            move.supply_line_id._sync_requested_with_moves()

    def _action_done(self, cancel_backorder=False):
        res = super()._action_done(cancel_backorder=cancel_backorder)
        self.supply_line_id._bump_to_done()
        return res


class StockPicking(models.Model):
    _inherit = ['stock.picking', 'external.user.stamp']
    _name = 'stock.picking'

    supply_order_id = fields.Many2one('supply.order', string='Supply Order', index='btree_not_null',
                                      compute='_compute_supply_order', store=True, readonly=False, copy=False)
    supply_ref = fields.Char(string='Supply Order No.', index=True,
                             compute='_compute_supply_ref', store=True, readonly=False)

    @api.depends('move_ids.supply_line_id.order_id')
    def _compute_supply_order(self):
        for picking in self:
            order = picking.move_ids.supply_line_id.order_id[:1]
            if order or not picking.supply_order_id:
                picking.supply_order_id = order

    @api.depends('supply_order_id.supply_ref')
    def _compute_supply_ref(self):
        for picking in self:
            if picking.supply_order_id:
                picking.supply_ref = picking.supply_order_id.supply_ref


class SaleOrder(models.Model):
    _inherit = ['sale.order', 'external.user.stamp', 'supply.adopt.mixin']
    _name = 'sale.order'

    supply_order_id = fields.Many2one('supply.order', string='Supply Order', index='btree_not_null', copy=False)
    supply_ref = fields.Char(string='Supply Order No.', index=True,
                             compute='_compute_supply_ref', store=True, readonly=False)

    @api.depends('supply_order_id.supply_ref')
    def _compute_supply_ref(self):
        for order in self:
            if order.supply_order_id:
                order.supply_ref = order.supply_order_id.supply_ref

    def _prepare_invoice(self):
        vals = super()._prepare_invoice()
        if self.supply_order_id:
            vals['supply_order_id'] = self.supply_order_id.id
        if self.supply_ref:
            vals['supply_ref'] = self.supply_ref
        return vals

    def _supply_order_vals(self, doc_lines):
        self.ensure_one()
        return {
            'partner_id': self.partner_id.id, 'company_id': self.company_id.id,
            'currency_id': self.currency_id.id, 'order_type': 'sale',
            'supply_ref': self.supply_ref or False,
            'line_ids': [Command.create({
                'product_id': l.product_id.id, 'qty_requested': l.product_uom_qty,
                'uom_id': l.product_uom_id.id, 'price_unit': l.price_unit, 'discount': l.discount,
                'tax_ids': [Command.set(l.tax_ids.ids)], 'sale_line_id': l.id,
            }) for l in doc_lines],
        }


